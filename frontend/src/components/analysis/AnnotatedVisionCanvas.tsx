import React, { useState } from 'react';
import type { DetectionItem } from '../../types/analysis';
import { Eye, EyeOff, Layers, CheckCircle2 } from 'lucide-react';

interface AnnotatedVisionCanvasProps {
  imageUrl: string;
  annotatedImageUrl?: string;
  detections: DetectionItem[];
  selectedClass?: string | null;
  onSelectDetection?: (detection: DetectionItem | null) => void;
}

export const AnnotatedVisionCanvas: React.FC<AnnotatedVisionCanvasProps> = ({
  imageUrl,
  annotatedImageUrl,
  detections,
  selectedClass,
  onSelectDetection,
}) => {
  const [showBoxes, setShowBoxes] = useState(true);
  const [showLabels, setShowLabels] = useState(true);
  const [hoveredId, setHoveredId] = useState<string | null>(null);
  const [viewMode, setViewMode] = useState<'interactive' | 'opencv'>(
    annotatedImageUrl ? 'opencv' : 'interactive'
  );

  const filteredDetections = selectedClass
    ? detections.filter((d) => d.material_class === selectedClass)
    : detections;

  const currentDisplayImage = viewMode === 'opencv' && annotatedImageUrl ? annotatedImageUrl : imageUrl;
  const isInteractiveMode = viewMode === 'interactive' || !annotatedImageUrl;

  return (
    <div className="relative rounded-2xl overflow-hidden border border-slate-200 bg-slate-950 shadow-xl group select-none">
      {/* Controls Bar */}
      <div className="absolute top-3 left-3 right-3 z-20 flex flex-wrap items-center justify-between gap-2 pointer-events-auto">
        <div className="flex items-center gap-2 bg-slate-900/80 backdrop-blur-md px-3 py-1.5 rounded-lg border border-slate-700/60 text-xs text-white">
          <Layers className="w-3.5 h-3.5 text-emerald-400" />
          <span className="font-semibold">
            {filteredDetections.length} Objects Detected
          </span>
        </div>

        <div className="flex items-center gap-1.5 bg-slate-900/80 backdrop-blur-md p-1 rounded-lg border border-slate-700/60">
          {annotatedImageUrl && (
            <div className="flex items-center rounded bg-slate-800 p-0.5 mr-1 border border-slate-700">
              <button
                onClick={() => setViewMode('opencv')}
                className={`px-2 py-0.5 rounded text-[11px] font-medium transition-colors ${
                  viewMode === 'opencv' ? 'bg-emerald-600 text-white' : 'text-slate-300 hover:text-white'
                }`}
                title="View OpenCV annotated image directly generated by FastAPI"
              >
                OpenCV Image
              </button>
              <button
                onClick={() => setViewMode('interactive')}
                className={`px-2 py-0.5 rounded text-[11px] font-medium transition-colors ${
                  viewMode === 'interactive' ? 'bg-emerald-600 text-white' : 'text-slate-300 hover:text-white'
                }`}
                title="View interactive SVG overlays with hover details"
              >
                Interactive
              </button>
            </div>
          )}

          {isInteractiveMode && (
            <>
              <button
                onClick={() => setShowBoxes(!showBoxes)}
                className={`px-2.5 py-1 rounded text-xs font-medium flex items-center gap-1 transition-colors ${
                  showBoxes ? 'bg-emerald-600 text-white' : 'text-slate-300 hover:text-white'
                }`}
                title="Toggle Bounding Boxes"
              >
                {showBoxes ? <Eye className="w-3.5 h-3.5" /> : <EyeOff className="w-3.5 h-3.5" />}
                <span>Boxes</span>
              </button>

              <button
                onClick={() => setShowLabels(!showLabels)}
                className={`px-2.5 py-1 rounded text-xs font-medium transition-colors ${
                  showLabels ? 'bg-emerald-600 text-white' : 'text-slate-300 hover:text-white'
                }`}
                title="Toggle Confidence Labels"
              >
                Labels
              </button>
            </>
          )}
        </div>
      </div>

      {/* Image & SVG Overlay Container */}
      <div className="relative w-full aspect-4/3 sm:aspect-16/10 flex items-center justify-center bg-slate-900">
        <img
          src={currentDisplayImage}
          alt="Analyzed Construction Debris"
          className="w-full h-full object-cover"
        />

        {/* SVG Bounding Boxes Overlay (only active in interactive mode) */}
        {isInteractiveMode && showBoxes && (
          <svg
            className="absolute inset-0 w-full h-full pointer-events-none"
            viewBox="0 0 100 100"
            preserveAspectRatio="none"
          >
            {filteredDetections.map((item) => {
              const [xMin, yMin, xMax, yMax] = item.bbox;
              const width = xMax - xMin;
              const height = yMax - yMin;
              const isHovered = hoveredId === item.id;

              return (
                <g key={item.id} className="pointer-events-auto cursor-pointer">
                  {/* Bounding Box Rect */}
                  <rect
                    x={xMin}
                    y={yMin}
                    width={width}
                    height={height}
                    fill={isHovered ? `${item.color}33` : `${item.color}15`}
                    stroke={item.color}
                    strokeWidth={isHovered ? 0.8 : 0.5}
                    rx="0.5"
                    className="transition-all duration-200"
                    onMouseEnter={() => {
                      setHoveredId(item.id);
                      onSelectDetection?.(item);
                    }}
                    onMouseLeave={() => {
                      setHoveredId(null);
                      onSelectDetection?.(null);
                    }}
                  />

                  {/* Corner Accent Dots */}
                  <circle cx={xMin} cy={yMin} r="0.6" fill={item.color} />
                  <circle cx={xMax} cy={yMin} r="0.6" fill={item.color} />
                  <circle cx={xMin} cy={yMax} r="0.6" fill={item.color} />
                  <circle cx={xMax} cy={yMax} r="0.6" fill={item.color} />
                </g>
              );
            })}
          </svg>
        )}

        {/* HTML Labels Placed Absolutely for Crisp Typography (interactive mode only) */}
        {isInteractiveMode &&
          showBoxes &&
          showLabels &&
          filteredDetections.map((item) => {
            const [xMin, yMin] = item.bbox;
            const isHovered = hoveredId === item.id;

            return (
              <div
                key={`lbl-${item.id}`}
                style={{
                  left: `${Math.max(1, Math.min(85, xMin))}%`,
                  top: `${Math.max(2, Math.min(92, yMin))}%`,
                  transform: 'translateY(-100%)',
                  backgroundColor: item.color,
                  color: '#ffffff',
                }}
                onMouseEnter={() => {
                  setHoveredId(item.id);
                  onSelectDetection?.(item);
                }}
                onMouseLeave={() => {
                  setHoveredId(null);
                  onSelectDetection?.(null);
                }}
                className={`absolute z-10 pointer-events-auto cursor-pointer text-[10px] sm:text-xs font-bold px-2 py-0.5 rounded shadow-lg transition-all duration-200 flex items-center gap-1 ${
                  isHovered
                    ? 'scale-110 ring-2 ring-white z-30'
                    : 'opacity-90 hover:opacity-100'
                }`}
              >
                <CheckCircle2 className="w-3 h-3 text-white" />
                <span>{item.label}</span>
                <span className="bg-black/30 px-1 py-0.2 rounded text-[9px] font-mono">
                  {Math.round(item.confidence * 100)}%
                </span>
              </div>
            );
          })}
      </div>

      {/* Bottom Hint */}
      <div className="bg-slate-900/95 px-4 py-2 text-[11px] text-slate-400 flex items-center justify-between border-t border-slate-800">
        <span>Hover or tap bounding boxes to inspect class probabilities</span>
        <span className="text-emerald-400 font-mono">Normalized Coordinate Overlay</span>
      </div>
    </div>
  );
};
